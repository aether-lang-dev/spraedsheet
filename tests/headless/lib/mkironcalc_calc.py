# Writes the IronCalc calc_tests material the headless harness reads (it loads
# modules, not files): from the workbooks in third_party/ironcalc/fixtures/calc_tests/
# (copied unchanged, see third_party/ironcalc/PROVENANCE.md), one module of base64
# per group, tests/headless/lib/ironcalc_calc_<group>.ts, and one test beside it,
# tests/headless/sheet_ironcalc_calc_<group>.ts, that opens each and compares every
# formula cell with the value Excel stored (a group is a folder, or the workbooks at
# the top; ARABIC_ROMAN, 40,000 cells, is a group of its own: a test has a minute).
#   python3 tests/headless/lib/mkironcalc_calc.py
import base64, os, re
here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, "..", "..", "..", "third_party", "ironcalc", "fixtures", "calc_tests")
groups = {}
for d, _, fs in sorted(os.walk(src)):
    for f in sorted(fs):
        if f.endswith(".xlsx"):
            rel = os.path.relpath(os.path.join(d, f), src)
            g = "roman" if f == "ARABIC_ROMAN.xlsx" else (rel.split("/")[0].lower() if "/" in rel else "top")
            groups.setdefault(g, []).append(rel)
for g, files in groups.items():
    mod = ["// Generated by mkironcalc_calc.py from third_party/ironcalc/fixtures/calc_tests/ (%s)" % g,
           "// (IronCalc, MIT; third_party/ironcalc/PROVENANCE.md). Do not edit.",
           "export const FIXTURES: [string, string][] = ["]
    for rel in files:
        mod.append('  ["%s", "%s"],' % (rel, base64.b64encode(open(os.path.join(src, rel), "rb").read()).decode()))
    mod.append("];")
    open(os.path.join(here, "ironcalc_calc_%s.ts" % g), "w").write("\n".join(mod) + "\n")
    test = '''// Formula compatibility workbooks from IronCalc, group "%s" (docs/comparisons/IRONCALC.md
// action 2; third_party/ironcalc/PROVENANCE.md): workbooks Excel saved, with the value it
// worked out stored beside each formula. Each is opened here, and every formula cell must
// come out as Excel's stored value, but for the cells listed in lib/ironcalc_calc_known.ts
// (with how they differ): a listed cell that comes right is reported, so the list shrinks
// as the functions are fixed. The assertions are ours; the workbooks are IronCalc's, byte
// for byte. (tests/headless/lib/mkironcalc_calc.py writes this file and its fixtures.)
import { FIXTURES } from "./lib/ironcalc_calc_%s.ts";
import { KNOWN } from "./lib/ironcalc_calc_known.ts";
import { disagreements } from "./lib/ironcalc_cached.ts";
import { eq } from "./lib/check.ts";

let total = 0;
for (const [name, b64] of FIXTURES) {
  const { diffs, checked } = await disagreements(name, b64);
  total += checked;
  const known = KNOWN[name] ?? {};
  const now = new Map(diffs.map((d): [string, string] => [d.cell, d.kind]));
  // fresh: differs and not listed; gone: listed and now right; changed: listed, differs another way
  const fresh = [...now].filter(([c]) => !(c in known)).map(([c, k]) => `${c} (${k})`);
  const gone = Object.keys(known).filter((c) => !now.has(c));
  const changed = [...now].filter(([c, k]) => c in known && known[c] !== k).map(([c, k]) => `${c} (${known[c]} -> ${k})`);
  eq(name, [fresh, gone, changed], [[], [], []]);
}
eq("every workbook was opened and its formulas compared", total > 0, true);

''' % (g, g)
    test += "".join("// expect: ok %s\n" % n for n in files) + "// expect: ok every workbook was opened and its formulas compared\n"
    open(os.path.join(here, "..", "sheet_ironcalc_calc_%s.ts" % g), "w").write(test)
print({g: len(f) for g, f in groups.items()})
