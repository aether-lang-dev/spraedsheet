# Writes tests/headless/lib/ironcalc_calc_fixtures.ts: the IronCalc calc_tests
# workbooks in third_party/ironcalc/fixtures/calc_tests/ (copied unchanged, see
# third_party/ironcalc/PROVENANCE.md) as base64, since the headless harness
# reads modules, not files.
#   python3 tests/headless/lib/mkironcalc_calc.py
import base64, os
here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, "..", "..", "..", "third_party", "ironcalc", "fixtures", "calc_tests")
out = ["// Generated by mkironcalc_calc.py from third_party/ironcalc/fixtures/calc_tests/**/*.xlsx",
       "// (IronCalc, MIT; third_party/ironcalc/PROVENANCE.md). Do not edit.",
       "export const CALC_FIXTURES: [string, string][] = ["]
for d, _, fs in sorted(os.walk(src)):
    for f in sorted(fs):
        if f.endswith(".xlsx"):
            p = os.path.join(d, f)
            out.append('  ["%s", "%s"],' % (os.path.relpath(p, src), base64.b64encode(open(p, "rb").read()).decode()))
out.append("];")
open(os.path.join(here, "ironcalc_calc_fixtures.ts"), "w").write("\n".join(out) + "\n")
