// The function status page (docs/comparisons/GNUMERIC.md action 1), printed as
// Markdown: tools/function-status.sh writes it to docs/function_status.md, and
// with --check (run-tests.sh's function_status) fails if the committed page is
// not what this prints now. It reads only what the tests and the library hold:
// each function's record (app/sheet/funcinfo.ts), its examples and boundary cases
// (tests/headless/lib/examples.ts, worked out here as sheet_examples does), and
// the cells of IronCalc's Excel-authored workbooks that still differ (DIFFERS,
// from the ledger tests/headless/lib/ironcalc_calc_known.ts).
import { allFunctions, DIFFERS } from "./sheet/funcinfo.ts";
import { CASES, check } from "./lib/examples.ts";

const all = allFunctions();
const cell = (s: string) => s.replace(/\|/g, "\\|");
const shown = (v: unknown) => typeof v === "string" ? (v.startsWith("#") ? v : JSON.stringify(v)) : typeof v === "number" ? String(Number(v.toPrecision(12))) : String(v);
let cases = 0, passing = 0, withCases = 0, differing = 0, cellsDiffering = 0;
const rows: string[] = [];
for (const f of all) {
  const mine = CASES[f.name] ?? [];
  let ok = 0;
  for (const [src, want] of mine) if (check(src, want).ok) ok++;
  cases += mine.length; passing += ok;
  if (mine.length) withCases++;
  const d = DIFFERS[f.name] ?? 0;
  if (d) { differing++; cellsDiffering += d; }
  const status = !mine.length ? "no cases" : ok === mine.length ? "passes" : `${mine.length - ok} failing`;
  const example = mine.length ? `\`${cell(mine[0][0])}\` = ${cell(shown(mine[0][1]))}` : "";
  const notes = [f.volatile ? "volatile" : "", f.refusesLogicals ? "TRUE/FALSE refused" : ""].filter(Boolean).join(", ");
  rows.push(`| ${f.name} | ${f.kind} | ${f.arity || "(its own)"} | ${status} | ${mine.length} | ${example} | ${d || ""} | ${notes} |`);
}
const lines = [
  "# Function status",
  "",
  "Generated by `tools/function-status.sh` from the library's records (`app/sheet/funcinfo.ts`),",
  "the examples and boundary cases (`tests/headless/lib/examples.ts`, checked by headless",
  "`sheet_examples`) and the IronCalc ledger (`tests/headless/lib/ironcalc_calc_known.ts`,",
  "`docs/comparisons/COMPATIBILITY.md`). Do not edit it: run the script. `./run-tests.sh`",
  "fails while this page is not what the script prints (`function_status`).",
  "",
  `${all.length} functions and forms; ${withCases} with an example and boundary cases (${cases} cases, ${passing} passing);`,
  `${differing} with cells of IronCalc's Excel-authored workbooks that still differ from Excel's stored value (${cellsDiffering}, a cell counted for each function its workbook names).`,
  "",
  "Columns: **status**, the cases worked out now; **cases**, how many; **example**, the first case and",
  "its value as its definition gives it (never another spreadsheet's output); **differs**, the ledger's",
  "cells for the function (unverified until looked at: COMPATIBILITY.md).",
  "",
  "| function | kind | takes | status | cases | example | differs | notes |",
  "|---|---|---|---|---|---|---|---|",
  ...rows,
];
for (const l of lines) print(l);
